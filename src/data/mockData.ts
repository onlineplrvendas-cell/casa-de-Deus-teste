// Helper to generate ISO strings offset by days or months relative to today
function getOffsetDate(daysOffset: number, monthsOffset: number = 0, hour: number = 10, minute: number = 0): string {
  const sp = getNowInSaoPaulo();
  const d = new Date(sp.getFullYear(), sp.getMonth() + monthsOffset, sp.getDate() + daysOffset, hour, minute);
  return d.toISOString();
}

function getOffsetDayString(daysOffset: number): string {
  const sp = getNowInSaoPaulo();
  const d = new Date(sp.getFullYear(), sp.getMonth(), sp.getDate() + daysOffset);
  const y = d.getFullYear();
  const m = String(d.getMonth() + 1).padStart(2, '0');
  const day = String(d.getDate()).padStart(2, '0');
  return `${y}-${m}-${day}`;
}

